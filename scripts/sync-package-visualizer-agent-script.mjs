import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildAgentScriptArtifacts,
  normalizeAgentScriptSource
} from "./package-visualizer-agent-script-parser.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "..");
const defaultSource = resolve(
  repositoryRoot,
  "../Package Visualizer + ISV Tooling Agentforce Extension/my-unpackaged-directory/aiAuthoringBundles/Package_Visualizer_Agent/Package_Visualizer_Agent.agent"
);
const defaultOutput = resolve(
  repositoryRoot,
  "force-app/main/default/lwc/inAppGuidanceCard/packageVisualizerAgentScriptGenerated.js"
);
const sourceVersion = 6;
const packagedApexClasses = new Set([
  "AgentforcePackagePortfolioAction",
  "AgentforcePackageDetailAction",
  "AgentforcePackageBuildDiagnosisAction",
  "AgentforcePackageBuildComparisonAction",
  "AgentforcePushRequestAnalysisAction",
  "AgentforcePushJobDiagnosisAction",
  "AgentforcePushRequestComparisonAction",
  "AgentforceSubscriberSupportAction",
  "AgentforcePackageVersionReadinessAction"
]);

function argumentValue(name, fallback) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : resolve(process.argv[index + 1]);
}

const sourcePath = argumentValue("--source", defaultSource);
const outputPath = argumentValue("--output", defaultOutput);
const checkOnly = process.argv.includes("--check");

if (!existsSync(sourcePath)) {
  throw new Error(`Canonical AgentScript not found: ${sourcePath}`);
}

const authoringSource = normalizeAgentScriptSource(
  readFileSync(sourcePath, "utf8")
);
const discoveredApexClasses = new Set();
let discoveredApexTargetCount = 0;
const source = authoringSource.replace(
  /target: "apex:\/\/(?:pkgviz__)?([A-Za-z][A-Za-z0-9_]*)"/g,
  (target, className) => {
    if (!packagedApexClasses.has(className)) {
      throw new Error(`Unexpected Apex target in AgentScript: ${target}`);
    }
    discoveredApexTargetCount += 1;
    discoveredApexClasses.add(className);
    return `target: "apex://pkgviz__${className}"`;
  }
);

if (
  discoveredApexTargetCount !== packagedApexClasses.size ||
  discoveredApexClasses.size !== packagedApexClasses.size ||
  [...packagedApexClasses].some(
    (className) => !discoveredApexClasses.has(className)
  )
) {
  throw new Error(
    `Expected exactly ${packagedApexClasses.size} Package Visualizer Apex targets for version ${sourceVersion}; found ${discoveredApexTargetCount}.`
  );
}

const sourceHash = createHash("sha256").update(source).digest("hex");
const { manifest, coachingEvidence, publicChatSummary } =
  buildAgentScriptArtifacts(source);
const generated =
  `// Generated by scripts/sync-package-visualizer-agent-script.mjs. Do not edit.\n` +
  `export const PACKAGE_VISUALIZER_AGENT_SCRIPT_SOURCE_VERSION = ${sourceVersion};\n` +
  `export const PACKAGE_VISUALIZER_AGENT_SCRIPT_SHA256 =\n  ${JSON.stringify(
    sourceHash
  )};\n` +
  `// prettier-ignore\n` +
  `export const PACKAGE_VISUALIZER_AGENT_SCRIPT = ${JSON.stringify(
    source
  )};\n` +
  `// prettier-ignore\n` +
  `export const PACKAGE_VISUALIZER_AGENT_SCRIPT_MANIFEST = ${JSON.stringify(
    manifest
  )};\n` +
  `// prettier-ignore\n` +
  `export const PACKAGE_VISUALIZER_AGENT_SCRIPT_COACHING_EVIDENCE = ${JSON.stringify(
    coachingEvidence
  )};\n` +
  `// prettier-ignore\n` +
  `export const PACKAGE_VISUALIZER_AGENT_SCRIPT_PUBLIC_CHAT_SUMMARY = ${JSON.stringify(
    publicChatSummary
  )};\n`;

if (checkOnly) {
  if (!existsSync(outputPath)) {
    throw new Error(`Generated AgentScript module not found: ${outputPath}`);
  }
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) {
    const currentHash = createHash("sha256").update(current).digest("hex");
    throw new Error(
      `AgentScript drift detected. Source SHA-256: ${sourceHash}; generated module SHA-256: ${currentHash}. Run this script without --check.`
    );
  }
  console.log(`AgentScript module is synchronized (${sourceHash}).`);
} else {
  writeFileSync(outputPath, generated, "utf8");
  console.log(`Generated ${outputPath} from ${sourcePath} (${sourceHash}).`);
}
